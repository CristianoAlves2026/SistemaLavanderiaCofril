    public void preenchetabeArquivos() {

        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Últimos Backup's"};

        File arquivo = new File("C:/Users/Lavanderia/Documents/BackupSistemaLavanderia");
        File[] file = arquivo.listFiles();

        if (file != null) {
            int length = file.length;

            for (int i = 0; i < length; ++i) {
                File f = file[i];

                if (f.isFile()) {
                    if (!f.getName().equals("BackUp.bat")){
                        dados.add(new Object[]{f.getName()});
                    }
                    
                } else if (f.isDirectory()) {
                    System.out.println("Diretorio: " + f.getName());
                }
            }

        }

        

        ModeloTabela tabelaarquivos = new ModeloTabela(dados, colunas);
        jTableArquivos.setModel(tabelaarquivos);
        jTableArquivos.getColumnModel().getColumn(0).setPreferredWidth(450);

        jTableArquivos.setAutoResizeMode(jTableArquivos.AUTO_RESIZE_OFF);
        jTableArquivos.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTableArquivos.setAutoCreateRowSorter(true);

    }

