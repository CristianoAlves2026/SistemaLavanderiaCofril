    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed
        try {
            
            
            /*Class.forName("com.mysql.jdbc.Driver");
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost/bdlavanderia", "root", "");*/
            conexao.getConexaoSql();
            
            
            String emp = modelo.buscaCodigoempreas((String) jComboBoxEmpresas.getSelectedItem());
            String dep = modelo.buscaCodigoDepartamentos((String) jComboBoxDepartamentos.getSelectedItem());
            
            if (jRadioButtonNumero.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo,empre.emp_razao, depar.dep_descricao, func.fun_admissao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_emp_cod = '"+ emp + "' and func.fun_status = 'ATIVO' and func.fun_dep_cod = '"+ dep + "' order by func.fun_sexo, func.fun_num  ");
            }else if (jRadioButtonNome.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo,empre.emp_razao, depar.dep_descricao, func.fun_admissao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_emp_cod = '"+ emp + "' and func.fun_status = 'ATIVO' and func.fun_dep_cod = '"+ dep + "' order by func.fun_nome ");
            }else if (jRadioButtonMasculino.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo,empre.emp_razao, depar.dep_descricao, func.fun_admissao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_sexo = 'MASCULINO' and func.fun_emp_cod = '"+ emp + "' and func.fun_status = 'ATIVO' and func.fun_dep_cod = '"+ dep + "' order by func.fun_sexo, func.fun_num ");
            }else if (jRadioButtonFeminino.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo,empre.emp_razao, depar.dep_descricao, func.fun_admissao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_sexo = 'FEMININO' and func.fun_emp_cod = '"+ emp + "' and func.fun_status = 'ATIVO' and func.fun_dep_cod = '"+ dep + "' order by func.fun_sexo, func.fun_num ");
            }
            
            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);
            
            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/Funcionario-Setor.jasper";
            //JasperReport jr = JasperCompileManager.compileReport(reportPath);
            JasperReport jr = (JasperReport) JRLoader.loadObjectFromFile(reportPath);
            
            HashMap map = new HashMap();
            map.put("funcSetor", Integer.parseInt(emp));
            map.put("funcEmpresa", Integer.parseInt(dep));
            //1º - nome do parametro criado no JasperSoft
                    //2º - parametro a ser passado para o relatório
       
            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();
            //con.close();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButtonGerarActionPerformed

