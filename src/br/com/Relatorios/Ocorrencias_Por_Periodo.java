    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed
            try {
            
            conexao.getConexaoSql();
            conexao.executaSql("SELECT o.oco_cod, o.oco_num, o.oco_data, o.oco_descricao, o.oco_acao, f.fun_nome, d.dep_descricao, e.emp_razao FROM ocorrencias as o inner join funcionarios as f on o.oco_num = f.fun_num inner join departamentos as d on f.fun_dep_cod = d.dep_cod inner join empresas as e on f.fun_emp_cod = e.emp_cod where oco_data >= '"+ dataformat.format(jDateChooserDataInicial.getDate()) +"' and oco_data <= '"+ dataformat.format(jDateChooserDataFinal.getDate()) +"' order by o.oco_data asc");

            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);

            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/Ocorrencias_Mes.jasper";
            //JasperReport jr = JasperCompileManager.compileReport(reportPath);
            JasperReport jr = (JasperReport) JRLoader.loadObjectFromFile(reportPath);

            
            HashMap map = new HashMap();
            map.put("DataIni", dataformat.format(jDateChooserDataInicial.getDate()));
            map.put("DataFim", dataformat.format(jDateChooserDataFinal.getDate()));
            
                        
            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();

        } catch (Exception ex) {
            ex.printStackTrace();

        }
    }//GEN-LAST:event_jButtonGerarActionPerformed

