    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed
        try {
            
            conexao.getConexaoSql();
            
            String emp = modelo.buscaCodigoempreas((String) jComboBoxEmpresas.getSelectedItem());
            
            
            if (jRadioButtonNumero.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo, empre.emp_razao, depar.dep_descricao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_emp_cod = '" + emp + "' and func.fun_status='ATIVO' order by func.fun_num, depar.dep_descricao, func.fun_sexo");
            }else if (jRadioButtonNome.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo, empre.emp_razao, depar.dep_descricao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_emp_cod = '" + emp + "' and func.fun_status='ATIVO' order by func.fun_nome, depar.dep_descricao, func.fun_sexo");
            }else if (jRadioButtonDepart.isSelected()){
                conexao.executaSql("select func.fun_num, func.fun_nome, func.fun_sexo, empre.emp_razao, depar.dep_descricao from funcionarios as func inner join empresas as empre on func.fun_emp_cod = empre.emp_cod inner join departamentos as depar on func.fun_dep_cod = depar.dep_cod where  func.fun_emp_cod = '" + emp + "' and func.fun_status='ATIVO' order by depar.dep_descricao, func.fun_num, func.fun_sexo");
            }
            
            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);
            
            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/Funcionario-Empresa.jasper";
            //JasperReport jr = JasperCompileManager.compileReport(reportPath);
            JasperReport jr = (JasperReport) JRLoader.loadObjectFromFile(reportPath);
            
            HashMap map = new HashMap();
            map.put("funcSetor", Integer.parseInt(emp));
            
            //1º - nome do parametro criado no JasperSoft
                    //2º - parametro a ser passado para o relatório
       
            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();
            //con.close();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButtonGerarActionPerformed

