    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed
        try {

            conexao.getConexaoSql();
            conexao.executaSql("select u.uni_descricao,u.peso_gramas, count(*),  round(u.peso_gramas * count(*)/1000,3) from lancamentos as l \n"
                    + "inner join uniformes as u on l.lan_uni_cod = u.uni_cod \n"
                    + "inner join tamanhos as t on l.lan_tam_cod = t.tam_cod \n"
                    + "where l.lan_sta_cod = 2\n"
                    + "and l.lan_data_baixa   >= '"+ dataformat.format(jDateChooserInicial.getDate()) +"'\n"
                    + "and l.lan_data_baixa  <= '"+ dataformat.format(jDateChooserFinal.getDate()) +"'\n"
                    + "GROUP BY uni_descricao ORDER BY uni_descricao");

            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);

            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/Descartes_de_Uniformes_peso.jasper";
            //JasperReport jr = JasperCompileManager.compileReport(reportPath);
            JasperReport jr = (JasperReport) JRLoader.loadObjectFromFile(reportPath);
            
            HashMap map = new HashMap();
            map.put("datainicial", dataformat.format(jDateChooserInicial.getDate()));
            map.put("datafinal", dataformat.format(jDateChooserFinal.getDate()));

            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();

        } catch (Exception ex) {
            ex.printStackTrace();

        }

    }//GEN-LAST:event_jButtonGerarActionPerformed

