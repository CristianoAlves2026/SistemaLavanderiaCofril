    public void preencherTabelaDetalharDados(String sql) {
        ArrayList dadoslin = new ArrayList();
        String[] colunascol = new String[]{"ID", "Número", "Funcionário", "Uniforme", "Tamanho", "Dias Uso", "Entrega", "Data Baixa"};

        conexao.getConexaoSql();
        conexao.executaSql(sql);
        int cont = 0;
        int contgeral = 0;
        String sigla;
        try {

            conexao.rs.first();
            sigla = conexao.rs.getString("t.tam_sigla");

            do {

                if (!conexao.rs.getString("t.tam_sigla").equals(sigla)) {
                    dadoslin.add(new Object[]{"", "", "", "", "", "", "", "SUB-T.: " + cont});
                    dadoslin.add(new Object[]{"", "", "", "", "", "", "", ""});
                    sigla = conexao.rs.getString("t.tam_sigla");
                    cont = 0;
                }

                dadoslin.add(new Object[]{conexao.rs.getInt("l.lan_cod"), conexao.rs.getInt("l.lan_fun_num") + " - " + conexao.rs.getString("l.lan_letra"), conexao.rs.getString("f.fun_nome"), conexao.rs.getString("u.uni_descricao"), conexao.rs.getString("t.tam_sigla"), conexao.rs.getInt("l.lan_dias_uso"), conexao.rs.getDate("l.lan_data_entrega"), conexao.rs.getDate("l.lan_data_baixa")});
                cont++;
                contgeral++;
            } while (conexao.rs.next());

            dadoslin.add(new Object[]{"", "", "", "", "", "", "", "SUB-T.: " + cont});
            dadoslin.add(new Object[]{"", "", "", "", "", "", "", ""});
            dadoslin.add(new Object[]{"", "", "", "", "", "", "", ""});
            dadoslin.add(new Object[]{"", "", "", "", "", "", "", "TOTAL..: " + contgeral});

            ModeloTabela modelotabDados = new ModeloTabela(dadoslin, colunascol);
            jTableUniformes.setModel(modelotabDados);

            jTableUniformes.getColumnModel().getColumn(0).setPreferredWidth(50);
            jTableUniformes.getColumnModel().getColumn(1).setPreferredWidth(50);
            jTableUniformes.getColumnModel().getColumn(2).setPreferredWidth(180);
            jTableUniformes.getColumnModel().getColumn(3).setPreferredWidth(200);
            jTableUniformes.getColumnModel().getColumn(4).setPreferredWidth(50);
            jTableUniformes.getColumnModel().getColumn(5).setPreferredWidth(50);
            jTableUniformes.getColumnModel().getColumn(6).setPreferredWidth(80);
            jTableUniformes.getColumnModel().getColumn(7).setPreferredWidth(80);
            jTableUniformes.setForeground(Color.blue);
            jTableUniformes.setFont(new Font("Tahoma", Font.PLAIN, 11));

            //jTableUniformes.setAutoResizeMode(jTableUniformes.AUTO_RESIZE_OFF);
            //jTableUniformes.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
            jTableUniformes.setAutoCreateRowSorter(true);

            conexao.FecharConexao();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Nenhum lançamento encontrado para detalhar consulta.");
        }
    }

    

