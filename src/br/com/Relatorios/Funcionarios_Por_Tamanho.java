    private void jButtonGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGerarActionPerformed
        if (jComboBoxEmpresas.getSelectedItem().equals("Selecione") || jComboBoxDepartamentos.getSelectedItem().equals("Selecione") )
            return;
        try {

            conexao.getConexaoSql();

            String emp = modelo.buscaCodigoempreas((String) jComboBoxEmpresas.getSelectedItem());
            String dep = modelo.buscaCodigoDepartamentos((String) jComboBoxDepartamentos.getSelectedItem());
            
            if (jComboBoxDepartamentos.isVisible()) {
                conexao.executaSql("select l.lan_fun_num, f.fun_nome, d.dep_descricao, e.emp_razao,  l.lan_data_entrega, u.uni_descricao, t.tam_sigla \n"
                        + "from lancamentos as l inner join funcionarios as f on l.lan_fun_num = f.fun_num\n"
                        + "inner join departamentos as d on d.dep_cod = f.fun_dep_cod\n"
                        + "inner join empresas as e on e.emp_cod = f.fun_emp_cod  \n"
                        + "inner join uniformes as u on l.lan_uni_cod = u.uni_cod \n"
                        + "inner join tamanhos as t on l.lan_tam_cod = t.tam_cod \n"
                        + "inner join status as s on l.lan_sta_cod = s.sta_cod \n"
                        + "where l.lan_letra = \"A\" and (l.lan_sta_cod = 1) and (uni_cod < 18 or uni_cod > 23)\n"
                        + "and  f.fun_emp_cod = '" + emp + "'\n"
                        + "and  f.fun_dep_cod = '" + dep + "'\n"
                        + "order by l.lan_fun_num, f.fun_nome  asc");
            } else {
                conexao.executaSql("select l.lan_fun_num, f.fun_nome, d.dep_descricao, e.emp_razao,  l.lan_data_entrega, u.uni_descricao, t.tam_sigla \n"
                        + "from lancamentos as l inner join funcionarios as f on l.lan_fun_num = f.fun_num\n"
                        + "inner join departamentos as d on d.dep_cod = f.fun_dep_cod\n"
                        + "inner join empresas as e on e.emp_cod = f.fun_emp_cod  \n"
                        + "inner join uniformes as u on l.lan_uni_cod = u.uni_cod \n"
                        + "inner join tamanhos as t on l.lan_tam_cod = t.tam_cod \n"
                        + "inner join status as s on l.lan_sta_cod = s.sta_cod \n"
                        + "where l.lan_letra = \"A\" and (l.lan_sta_cod = 1) and (uni_cod < 18 or uni_cod > 23)\n"
                        + "and  f.fun_emp_cod = '" + emp + "'\n"
                        + "order by l.lan_fun_num, d.dep_descricao, f.fun_nome  asc");

            }
            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);

            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/Func_Setor_Tamanhos.jasper";

            //JasperReport jr = JasperCompileManager.compileReport(reportPath);
            JasperReport jr = (JasperReport) JRLoader.loadObjectFromFile(reportPath);

            HashMap map = new HashMap();
            map.put("funcEmpresa", Integer.parseInt(emp));
            map.put("funcDepartamento", Integer.parseInt(dep));

            //1º - nome do parametro criado no JasperSoft
            //2º - parametro a ser passado para o relatório
            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();
            //con.close();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButtonGerarActionPerformed

    private void jComboBoxEmpresasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxEmpresasActionPerformed
        if (flag == 2 && !jComboBoxEmpresas.getSelectedItem().equals("Selecione")) {
            String emp = modelo.buscaCodigoempreas((String) jComboBoxEmpresas.getSelectedItem());
            if (Integer.parseInt(emp) > 1) {
                jLabel2.setVisible(false);
                jComboBoxDepartamentos.setVisible(false);
                jComboBoxDepartamentos.setSelectedItem("LAVANDERIA");  // só para não gerar erro quando buscar somente empresa
            } else {
                jLabel2.setVisible(true);
                jComboBoxDepartamentos.setVisible(true);
                jComboBoxDepartamentos.setSelectedItem("Selecione");
            }
        }
    }//GEN-LAST:event_jComboBoxEmpresasActionPerformed

