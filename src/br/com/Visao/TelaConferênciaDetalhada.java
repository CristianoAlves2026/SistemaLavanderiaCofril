    private void jButtonNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonNovoActionPerformed
        if (ValidaAcessos.valida(3) == 2) {
            return;
        }
        jLabelResto.setText("");
        jLabelStatus.setText("Atualizando...");

        int codemp = Integer.parseInt(preenche.buscaCodigoempreas((String) jComboBoxEmpresa.getSelectedItem()));
        confere.setCadconfemp(codemp);
        confere.setCadconfdata(new Date());
        controlconfere.novo(confere);
        preenchetabelacadastro();
        jTableCadastroConferencia.setRowSelectionInterval(0, 0);

        preenchetabelasetor(String.valueOf(codemp));
        jTableSetor.setRowSelectionInterval(0, 0);

        confere.setConfidcadastro(Integer.parseInt("" + jTableCadastroConferencia.getValueAt(jTableCadastroConferencia.getSelectedRow(), 0)));
        conexao.getConexaoSql();
        jProgressBarProcesso.setValue(0);
        jProgressBarProcesso.setMaximum(jTableSetor.getRowCount());

        jButtonNovo.setEnabled(false);
        jTableCadastroConferencia.setEnabled(false);
        jTableSetor.setEnabled(false);

        new Thread(new Runnable() {
            public void run() {
                do {

                    confere.setConfnum(Integer.parseInt("" + jTableSetor.getValueAt(jProgressBarProcesso.getValue(), 0)));

                    ////////////controlconfere.PovoTabelaConferencia(confere);
                    try {

                        PreparedStatement pst = conexao.connection.prepareStatement("insert into conferencia_detail (conf_id_cadastro, conf_numero) values (?,?) ");
                        pst.setInt(1, confere.getConfidcadastro());
                        pst.setInt(2, confere.getConfnum());
                        pst.execute();

                    } catch (SQLException ex) {
                        JOptionPane.showMessageDialog(null, "Erro ao cadastrar dados da nova conferência." + ex);
                    }
                    ///////////////////////////////                    
                    jProgressBarProcesso.setValue(jProgressBarProcesso.getValue() + 1);
                    //contador++;
                    barraprogresso(jProgressBarProcesso.getValue());

                } while (jProgressBarProcesso.getValue() < jTableSetor.getRowCount());
                conexao.FecharConexao();

                //JOptionPane.showMessageDialog(null, "Dados da nova confrência cadastrados com sucesso.");
                preenche();
                jTableCadastroConferencia.clearSelection();

            }
        }).start();


    }//GEN-LAST:event_jButtonNovoActionPerformed

