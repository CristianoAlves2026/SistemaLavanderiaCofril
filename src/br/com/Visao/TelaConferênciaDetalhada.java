    public void numeroPerdeFoco() {
        if (!jTextFieldNumero.getText().equals("")) {

            confere.setCadconfcod(Integer.parseInt("" + jTableCadastroConferencia.getValueAt(jTableCadastroConferencia.getSelectedRow(), 0)));
            confere.setConfnum(Integer.parseInt(jTextFieldNumero.getText()));

            controlconfere.buscaObsFuncionario(confere); // verifica na tabela funcionário se há observação para o numero.

            controlconfere.buscaNumFuncionario(confere);  // verifica na tabala conferência se o número digitado existe.

            if (confere.getConfstatus() == null) {
                confere.setConfstatus("nulo");
            }

            if (confere.getConfstatus().equals("OK") && confere.getConfnum() != - 1) {

                jTextFieldNumero.setEnabled(false);

                jLabelObs1.setForeground(new java.awt.Color(255, 0, 0));
                jLabelObs2.setForeground(new java.awt.Color(255, 0, 0));
                jLabelObs1.setText(jTextFieldNumero.getText());
                jLabelObs2.setText("Número Repetido");
                jTextFieldNumero.setText("");
                return;
            }

            if (confere.getConfnum() != - 1) {
                confere.setConfstatus("OK");
                confere.setTouca(jLabelLetraTouca.getText());
                confere.setBlusa(jLabelLetraBlusa.getText());
                confere.setCalça(jLabelLetraCalça.getText());

                jLabelObs1.setForeground(new java.awt.Color(0, 0, 204));
                jLabelObs2.setForeground(new java.awt.Color(0, 0, 204));
                if (confere.getConfobs().contains("PTM")) {
                    jPanel1.setBackground(new java.awt.Color(0, 0, 255));
                    jLabelObs1.setText(jTextFieldNumero.getText());
                    jLabelObs2.setText("Primeira Turma");
                    jTextFieldNumero.setEnabled(false);
                    confere.setConfobs("PRIMEIRA TURMA");
                    this.setTitle(jLabelObs1.getText() + " - " + confere.getConfobs());
                } else if (confere.getConfobs().contains("OBS")) {
                    jPanel1.setBackground(new java.awt.Color(51, 255, 255));
                    jLabelObs1.setText(jTextFieldNumero.getText());
                    jLabelObs2.setText("Observação");
                    jTextFieldNumero.setEnabled(false);
                    this.setTitle(jLabelObs1.getText() + " - " + confere.getConfobs());
                } else {
                    //jLabelObs1.setForeground(new java.awt.Color(0, 0, 0));
                    //jLabelObs2.setForeground(new java.awt.Color(0, 0, 0));
                    jLabelObs1.setText(jTextFieldNumero.getText());
                    jLabelObs2.setText("OK");
                    confere.setConfobs("");
                    this.setTitle("Conferência");
                }

                controlconfere.marcapeca(confere);

                int qtd = confere.getConftotal();
                qtd++;
                confere.setConftotal(qtd);
                jLabelPercent.setText(qtd + " de " + String.valueOf(jTableSetor.getRowCount()));

                int tot = Integer.parseInt(String.valueOf(jTableSetor.getRowCount()));
                int resto = tot - qtd;
                jLabelResto.setText("Faltam " + resto);
                preenche();

                jTableCadastroConferencia.setEnabled(false);
                jButtonNovo.setEnabled(false);
                jTextFieldNumero.setText("");
                jTextFieldNumero.requestFocus();
            } else {
                jTextFieldNumero.setText("");
                jTextFieldNumero.requestFocus();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Informe um número.");
            return;
        }
    }

    public void preenchetabelacadastro() {
        conexao.getConexaoSql();

        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"ID", "Empresa", "Data"};

        conexao.executaSql("Select cadf.cadconf_cod, emp.emp_razao, cadf.cadconf_data from cadastro_conferencia_detail as cadf inner join empresas as emp on cadf.cadconf_empresa = emp.emp_cod order by cadf.cadconf_cod desc");
        try {
            conexao.rs.first();
            do {

                dados.add(new Object[]{conexao.rs.getInt("cadconf_cod"), conexao.rs.getString("emp_razao"), dataformtada.format(conexao.rs.getDate("cadconf_data"))});
            } while (conexao.rs.next());

            ModeloTabela tabelaconf = new ModeloTabela(dados, colunas);
            jTableCadastroConferencia.setModel(tabelaconf);
            jTableCadastroConferencia.getColumnModel().getColumn(0).setPreferredWidth(50);
            jTableCadastroConferencia.getColumnModel().getColumn(1).setPreferredWidth(210);
            jTableCadastroConferencia.getColumnModel().getColumn(2).setPreferredWidth(200);
            jTableCadastroConferencia.setAutoResizeMode(jTableCadastroConferencia.AUTO_RESIZE_OFF);
            jTableCadastroConferencia.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Nenhum funcionário encontrado.");
        }

        conexao.FecharConexao();

    }

