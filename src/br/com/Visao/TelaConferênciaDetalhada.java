    private void jButtonPendenciasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPendenciasActionPerformed
        if (jTableCadastroConferencia.getSelectedRow() == - 1) {
            JOptionPane.showMessageDialog(null, "Selecione um cadastro na lista acima para emitir o realtório.");
            return;
        }

        try {
            int cadnum = Integer.parseInt("" + jTableCadastroConferencia.getValueAt(jTableCadastroConferencia.getSelectedRow(), 0));
            conexao.getConexaoSql();
            conexao.executaSql("Select c.conf_id_cadastro, c.conf_numero, c.conf_status, c.conf_obs from conferencia_detail as c where c.conf_id_cadastro = '" + cadnum + "' and c.conf_status != 'OK' order by c.conf_numero");

            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);

            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/conferencia.jasper";
            //JasperReport jr = JasperCompileManager.compileReport(reportPath);
            JasperReport jr = (JasperReport) JRLoader.loadObjectFromFile(reportPath);
            
            HashMap map = new HashMap();
            map.put("Num_Cadastro", cadnum);

            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();
            
        } catch (Exception ex) {
            ex.printStackTrace();

        }
    }//GEN-LAST:event_jButtonPendenciasActionPerformed

