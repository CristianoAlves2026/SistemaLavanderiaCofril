    public void marcarPendencia() {

        if (jTextFieldNumero.getText().trim().equals("")) {
            return;
        }

        try {

            int numero = Integer.parseInt(jTextFieldNumero.getText());

            int cadastro = Integer.parseInt("" + jTableCadastroConferencia
                    .getValueAt(jTableCadastroConferencia.getSelectedRow(), 0));

            conexao.getConexaoSql();

            PreparedStatement pst = conexao.connection.prepareStatement(
                    "UPDATE conferencia SET conf_status = 'PD' "
                    + "WHERE conf_numero = ? AND conf_id_cadastro = ?");

            pst.setInt(1, numero);
            pst.setInt(2, cadastro);

            int linhas = pst.executeUpdate();

            if (linhas == 0) {

                CustomBeep.beep(440, 300);
                JOptionPane.showMessageDialog(null,
                        "Número não encontrado nesta conferência.");

            } else {

                preenche();

                // acrescenta número no texto
                if (numerosPD.equals("PD: ")) {
                    numerosPD += numero;
                } else {
                    numerosPD += " | " + numero;
                }

                // cria só uma vez
                if (balaoPD == null || balaoPD.getParent() == null) {
                    balaoPD = new BalaoAnimado(numerosPD);
                    balaoPD.mostrar(this, 50, 180); // posição
                } else {
                    balaoPD.setTexto(numerosPD);
                }
            }

            conexao.FecharConexao();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null,
                    "Erro ao marcar pendência: " + e.getMessage());
        }

        jTextFieldNumero.setText("");
        jTextFieldNumero.requestFocus();
    }

    public boolean verificaPendencia() {

        boolean resultado = false;

        if (jTextFieldNumero.getText().trim().equals("")) {
            return false;
        }

        try {

            int numero = Integer.parseInt(jTextFieldNumero.getText());

            int cadastro = Integer.parseInt("" + jTableCadastroConferencia
                    .getValueAt(jTableCadastroConferencia.getSelectedRow(), 0));

            conexao.getConexaoSql();

            PreparedStatement pst = conexao.connection.prepareStatement(
                    "SELECT conf_status FROM conferencia "
                    + "WHERE conf_numero = ? AND conf_id_cadastro = ?");

            pst.setInt(1, numero);
            pst.setInt(2, cadastro);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {

                String status = rs.getString("conf_status");

                if ("PD".equals(status)) {
                    resultado = true;
                }

            }

            conexao.FecharConexao();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null,
                    "Erro ao verificar pendência: " + e.getMessage());

        }

        return resultado;
    }

