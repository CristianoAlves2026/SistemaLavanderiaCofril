    private void colorirTabelaPendencia() {

        jTableSetor.setDefaultRenderer(Object.class, new DefaultTableCellRenderer() {

            @Override
            public Component getTableCellRendererComponent(
                    JTable table, Object value, boolean isSelected,
                    boolean hasFocus, int row, int column) {

                Component c = super.getTableCellRendererComponent(
                        table, value, isSelected, hasFocus, row, column);

                Object valorStatus = null;

                if (table.getColumnCount() > 4 && row < table.getRowCount()) {
                    valorStatus = table.getValueAt(row, 4);
                }

                String status = valorStatus == null ? "" : valorStatus.toString();

                if (!isSelected) {

                    if ("PD".equals(status)) {

                        c.setBackground(new Color(255, 180, 180));

                    } else if ("OK".equals(status)) {

                        c.setBackground(new Color(180, 255, 180));

                    } else {

                        c.setBackground(Color.WHITE);
                    }
                }

                return c;
            }
        });
    }

    private void sincronizarBalaoPD() {

    StringBuilder sb = new StringBuilder();
    int count = 0;

    for (int i = 0; i < jTableSetor.getRowCount(); i++) {

        String status = String.valueOf(jTableSetor.getValueAt(i, 4));
        String numero = String.valueOf(jTableSetor.getValueAt(i, 0));

        if ("PD".equals(status)) {

            if (count > 0) {
                sb.append(" | ");
            }

            sb.append(numero);
            count++;
        }
    }

    numerosPD = sb.toString();

    String textoFinal = numerosPD;

    // ✔ se já existe, só atualiza texto (mantém posição)
    if (balaoPD != null && balaoPD.getParent() != null) {

        balaoPD.setTexto(textoFinal);

        // mantém posição atual sem reset
        balaoPD.setLocation(balaoPD.getX(), balaoPD.getY());

    } else {

        // cria só se não existir
        if (!textoFinal.isEmpty()) {
            balaoPD = new BalaoAnimado("");
            balaoPD.setTexto(textoFinal);
            balaoPD.mostrar(this, 140, 320);
        }
    }

    getLayeredPane().revalidate();
    getLayeredPane().repaint();
}

