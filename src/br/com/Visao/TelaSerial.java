    public void ValidaNumero(JTextField Numero) {
        long valor;
        if (Numero.getText().length() != 0) {
            try {
                valor = Long.parseLong(Numero.getText());
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(null, "Esse campo só aceita números.", "Informação", JOptionPane.INFORMATION_MESSAGE);
                Numero.grabFocus();
                Numero.setText("");
                Numero.requestFocus();
                
            }
        }
    }

    
    private void jButtonAcessarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAcessarActionPerformed
        
        ValidaNumero(jTextFieldSerial);
        
        if (jTextFieldSerial.getText().equals("")) {
            jTextFieldSerial.requestFocus();
            return;
        }
        

        Calendar data2 = new GregorianCalendar();
        String datas = dataformatada.format(new Date().getTime());

        try {
            data2.setTime(dataformatada.parse(datas));
        } catch (ParseException ex) {
            Logger.getLogger(TelaSerial.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
        
        long serial = Long.parseLong(jTextFieldSerial.getText());
        long miliseg = data2.getTimeInMillis();

        if (serial == miliseg) {
            dispose();
            JOptionPane.showMessageDialog(null, "Número de Licença Validado com Sucesso.");
            TelaPrincipal.recebefoco = 1;
            dispose();
        } else {
            JOptionPane.showMessageDialog(null, "Número da Licença Inválido.");
            jTextFieldSerial.setText(String.valueOf(data2.getTimeInMillis()));
            jTextFieldSerial.requestFocus();
            
        }


    }//GEN-LAST:event_jButtonAcessarActionPerformed

