    public void preencherTabelaTempoMedioFunc(String sql) {
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Número", "Funcionário", "Uniforme", "Tempo Médio"};

        conexao.getConexaoSql();
        conexao.executaSql(sql);

        try {

            conexao.rs.first();

            do {
                if (jRadioButtonMediaGeral.isSelected() == true) {
                    dados.add(new Object[]{"", "MÉDIA GERAL COFRIL", conexao.rs.getString("u.uni_descricao"), tempo(conexao.rs.getInt("(sum(l.lan_dias_uso))") / conexao.rs.getInt("count(*)"))});
                } else {
                    dados.add(new Object[]{conexao.rs.getInt("l.lan_fun_num"), conexao.rs.getString("f.fun_nome"), conexao.rs.getString("u.uni_descricao"), tempo(conexao.rs.getInt("(sum(l.lan_dias_uso))") / conexao.rs.getInt("count(*)"))});
                }
            } while (conexao.rs.next());

            ModeloTabela modelotab = new ModeloTabela(dados, colunas);
            jTableTempoMedio.setModel(modelotab);

            jTableTempoMedio.getColumnModel().getColumn(0).setPreferredWidth(50);
            jTableTempoMedio.getColumnModel().getColumn(1).setPreferredWidth(200);
            jTableTempoMedio.getColumnModel().getColumn(2).setPreferredWidth(200);
            jTableTempoMedio.getColumnModel().getColumn(3).setPreferredWidth(200);
            
            jTableTempoMedio.setFont(new Font("Tahoma", Font.PLAIN, 11));
            jTableTempoMedio.setForeground(Color.black);
            jTableTempoMedio.setAutoResizeMode(jTableTempoMedio.AUTO_RESIZE_OFF);
            jTableTempoMedio.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
            

            conexao.FecharConexao();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Nenhum lançamento encontrado para cálculo de tempo médio.");
        }
    }

