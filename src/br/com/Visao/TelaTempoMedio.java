    public String tempo(int qtddias) {

        int x, y, anos = 0, dias = 0, meses = 0;
        //String z = "" + jTableTempoMedio.getValueAt(jTableTempoMedio.getSelectedRow(), 3);
        //x = Integer.parseInt(z);
        x = qtddias;
        y = 0;

        anos = x / 360;
        y = x % 360;
        meses = y / 30;
        dias = y % 30;

        String tempo;
        if (anos == 0 && meses != 0) {
            tempo = meses + " mes(es) e " + dias + " dia(s)";
        } else if (anos == 0 && meses == 0) {
            tempo = dias + " dia(s).";
        } else if (dias == 0) {
            tempo = anos + " ano(s) e " + meses + " mes(es) ";
        } else if (meses == 0) {
            tempo = anos + " ano(s) e " + dias + " dia(s)";
        } else {
            tempo = anos + " ano(s), " + meses + " mes(es) e " + dias + " dia(s)";
        }
        return tempo;
    }

    public void preencherTabelaExpandirFunc(String sql) {
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"ID", "Número", "Funcionário", "Uniforme", "Dias Uso", "Entrega", "Data Baixa"};
        
        conexao.getConexaoSql();
        conexao.executaSql(sql);
        
        try {
            int totdias = 0;
            int totqtd = 0;
            conexao.rs.first();

            do {
                totdias = totdias + conexao.rs.getInt("l.lan_dias_uso");
                totqtd++;
                dados.add(new Object[]{conexao.rs.getInt("l.lan_cod"), conexao.rs.getInt("l.lan_fun_num") + " - " + conexao.rs.getString("l.lan_letra"), conexao.rs.getString("f.fun_nome"), conexao.rs.getString("u.uni_descricao"), conexao.rs.getInt("l.lan_dias_uso"), conexao.rs.getDate("l.lan_data_entrega"), conexao.rs.getDate("l.lan_data_baixa")});
                
            } while (conexao.rs.next());

           jLabelTotalDias.setText("Total de Dias : " + String.valueOf(totdias));
           jLabelTotalQtd.setText("Quantidade de Peças : " + String.valueOf(totqtd));
            ModeloTabela modelotab = new ModeloTabela(dados, colunas);
            jTableTempoMedio.setModel(modelotab);

            jTableTempoMedio.getColumnModel().getColumn(0).setPreferredWidth(50);
            jTableTempoMedio.getColumnModel().getColumn(1).setPreferredWidth(50);
            jTableTempoMedio.getColumnModel().getColumn(2).setPreferredWidth(180);
            jTableTempoMedio.getColumnModel().getColumn(3).setPreferredWidth(200);
            jTableTempoMedio.getColumnModel().getColumn(4).setPreferredWidth(80);
            jTableTempoMedio.getColumnModel().getColumn(5).setPreferredWidth(80);
            jTableTempoMedio.getColumnModel().getColumn(6).setPreferredWidth(80);

            jTableTempoMedio.setForeground(Color.blue);
            jTableTempoMedio.setFont(new Font("Tahoma", Font.PLAIN, 11));
            jTableTempoMedio.setAutoResizeMode(jTableTempoMedio.AUTO_RESIZE_OFF);
            jTableTempoMedio.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
            jTableTempoMedio.setAutoCreateRowSorter(true);

            conexao.FecharConexao();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Nenhum lançamento encontrado para expandir consulta.");
        }
    }

