    private void jButtonImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonImprimirActionPerformed
        try {
            String numero = jTextFieldNumero.getText();
            conexao.getConexaoSql();
            conexao.executaSql("select o.oco_cod, o.oco_num, o.oco_data, o.oco_descricao, o.oco_acao, f.fun_nome, d.dep_descricao, e.emp_razao FROM ocorrencias as o inner join funcionarios as f on o.oco_num = f.fun_num inner join departamentos as d on f.fun_dep_cod = d.dep_cod inner join empresas as e on f.fun_emp_cod = e.emp_cod where o.oco_num = '" + numero + "' order by o.oco_data desc");

            JRResultSetDataSource relatresult = new JRResultSetDataSource(conexao.rs);

            String reportPath = "C:/Users/Lavanderia/Documents/MyReports/Ocorrencias_Funcionario.jrxml";
            JasperReport jr = JasperCompileManager.compileReport(reportPath);

            HashMap map = new HashMap();
            map.put("Parameter_numero", numero);

            JasperPrint jp = JasperFillManager.fillReport(jr, map, relatresult);

            JasperViewer.viewReport(jp, false);
            conexao.FecharConexao();

        } catch (Exception ex) {
            ex.printStackTrace();

        }

    }//GEN-LAST:event_jButtonImprimirActionPerformed

