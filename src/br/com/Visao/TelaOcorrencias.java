    public void preencherTabelaOcorrencias() {
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"ID", "Data", "Numero", "Descrição", "Ação"};
        String data;
        conexao.getConexaoSql();

        int id = Integer.parseInt(jTextFieldCodigo.getText());
        conexao.executaSql("select * from ocorrencias where id_func = '" + id + "' order by oco_data desc");
        try {
            conexao.rs.first();

            do {

                dados.add(new Object[]{conexao.rs.getInt("oco_cod"), dataformatada.format(conexao.rs.getDate("oco_data").getTime()), conexao.rs.getInt("oco_num"), conexao.rs.getString("oco_descricao"), conexao.rs.getString("oco_acao")});

            } while (conexao.rs.next());

            ModeloTabela modelotab = new ModeloTabela(dados, colunas);
            jTableOcorrencias.setModel(modelotab);

            jTableOcorrencias.getColumnModel().getColumn(0).setPreferredWidth(50);
            jTableOcorrencias.getColumnModel().getColumn(1).setPreferredWidth(80);
            jTableOcorrencias.getColumnModel().getColumn(2).setPreferredWidth(60);
            jTableOcorrencias.getColumnModel().getColumn(3).setPreferredWidth(380);
            jTableOcorrencias.getColumnModel().getColumn(4).setPreferredWidth(280);

            jTableOcorrencias.setAutoResizeMode(jTableOcorrencias.AUTO_RESIZE_OFF);
            jTableOcorrencias.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
            jTableOcorrencias.setAutoCreateRowSorter(true);

            conexao.FecharConexao();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Nenhum lançamentos encontrado.");
        }

    }

