    public void preencherTabelaEstoque(){ 
        conexao.getConexaoSql();
        ArrayList dados = new ArrayList();
        conexao.executaSql("select max(tam_ordem) from tamanhos");
        int totcol;
           try {
               //////////////////////////////////////
               //PREENCHE AS COLUNA DO JTABLE
               //////////////////////////////////////
               conexao.rs.first();
               totcol = conexao.rs.getInt("max(tam_ordem)");
               String [] colunas = new String[totcol+1];
               //String [] linhasdecolunas = new String[totcol+1];
               colunas[0] = "Descrição"; 
               conexao.executaSql("select tam_sigla, tam_descricao from tamanhos order by tam_ordem");
               conexao.rs.first();
               for(int c=1; c<=totcol; c++){
                      colunas[c] = conexao.rs.getString("tam_sigla")+ "  " + conexao.rs.getString("tam_descricao");
                      conexao.rs.next();
               }
               
               //////////////////////////////////////
               //PREENCHE AS LINHAS DO JTABLE
               //////////////////////////////////////
               conexao.executaSql("select u.uni_descricao, t.tam_sigla, est_quantidade from estoque as e inner join uniformes as u on est_uni_cod = uni_cod inner join tamanhos as t on est_tam_cod = tam_cod order by u.uni_cod, t.tam_ordem");
               
              
               conexao.executaSqlu("select * from uniformes order by uni_descricao");
               conexao.rs_u.first();
               
               conexao.executaSqlt("select * from tamanhos order by tam_ordem");
               
               String uniforme;
               String tamanho;
               int soma = 0;
               
               do {  
                   String [] linhasdecolunas = new String[totcol+1];
                   uniforme = conexao.rs_u.getString("uni_descricao");
                   linhasdecolunas[0] = uniforme;
                   
                   int i = 1;
                   conexao.rs_t.first();
                   
                   do {
                           tamanho = conexao.rs_t.getString("tam_sigla");
                           conexao.rs.first();
                           
                            do{
                                if (uniforme.equals(conexao.rs.getString("uni_descricao")) && tamanho.equals(conexao.rs.getString("tam_sigla"))){
                                    soma = soma + conexao.rs.getInt("est_quantidade");
                                };
                            }while (conexao.rs.next());
                            if (soma == 0){
                                linhasdecolunas[i++] = "-";
                            }else {
                                linhasdecolunas[i++] = Integer.toString(soma);
                            }
                            soma = 0;
                       
                   }while (conexao.rs_t.next());
                   
                   dados.add(linhasdecolunas);
               }while (conexao.rs_u.next());
                 
                
               ModeloTabela modelotab = new ModeloTabela(dados, colunas);
               jTableEstoque.setModel(modelotab);
               jTableEstoque.getColumnModel().getColumn(0).setPreferredWidth(420);
               
               
           } catch (SQLException ex) {
               Logger.getLogger(TelaEstoque.class.getName()).log(Level.SEVERE, null, ex);
           }
        
    }    
    
     
      
        
        
        
   
    

