    public void preencherTabelaLancamentos(String sql) {
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Lançamentos"};
        
        conexao.getConexaoSql();
        conexao.executaSql(sql);
        
        try {
        
            conexao.rs.first();
            do {
                dados.add(new Object[]{conexao.rs.getString("rec_lancamento")});
            } while (conexao.rs.next());

            ModeloTabela modelotab = new ModeloTabela(dados, colunas);
            jTableRecentes.setModel(modelotab);
            
            
            jTableRecentes.getColumnModel().getColumn(0).setPreferredWidth(800);
            jTableRecentes.setFont(new Font("Tahoma", Font.PLAIN, 11));
            jTableRecentes.setAutoResizeMode(jTableRecentes.AUTO_RESIZE_OFF);
            jTableRecentes.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
            

            conexao.FecharConexao();
      
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Nenhum lançamento recente encontrado.");
        }

    }


