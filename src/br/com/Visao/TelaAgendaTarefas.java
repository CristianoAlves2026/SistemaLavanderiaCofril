    private void jButtonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonExcluirActionPerformed
        if (jTabletarefas.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(null, "Selecione uma tarefa para excluir.");
            return;
        }

        conexao.getConexaoSql();
        try {
            String ide = "" + jTabletarefas.getValueAt(jTabletarefas.getSelectedRow(), 0);

            PreparedStatement pst = conexao.connection.prepareStatement("delete from agenda_tarefas where id=?");
            pst.setInt(1, Integer.parseInt(ide));
            pst.execute();
            JOptionPane.showMessageDialog(null, "Tarefa excluida com sucesso. \n \n ");
            preencherTarefas();
            jDateChooserAgenda.setDate(null);
            jComboBoxStatus.setSelectedItem("Agendada");
            jTextFieldAssunto.setText(null);
            jTextPaneDescricao.setText(null);
            jComboBoxHora.setSelectedItem("0");
            jComboBoxMinuto.setSelectedItem("0");

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Erro ao excluir tarefa. \n \n " + ex);
        }

        conexao.FecharConexao();
    }//GEN-LAST:event_jButtonExcluirActionPerformed

