    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        if (jDateChooserAgenda.getDate() == null) {
            return;
        }

        if (jTextFieldAssunto.getText().equals("")) {
            return;
        } else if (jTextPaneDescricao.getText().equals("")) {
            return;
        }

        conexao.getConexaoSql();

        try {

            PreparedStatement pst = conexao.connection.prepareStatement("insert into agenda_tarefas (assunto, descricao, data_agendada, hora, minuto, status) values (?,?,?,?,?,?) ");
            pst.setString(1, jTextFieldAssunto.getText());
            pst.setString(2, jTextPaneDescricao.getText());
            pst.setDate(3, new java.sql.Date(jDateChooserAgenda.getDate().getTime()));
            pst.setInt(4, Integer.parseInt((String) jComboBoxHora.getSelectedItem()));
            pst.setInt(5, Integer.parseInt((String) jComboBoxMinuto.getSelectedItem()));
            pst.setString(6, (String) jComboBoxStatus.getSelectedItem());
            pst.execute();
            JOptionPane.showMessageDialog(null, "Nova tarefa agendada com sucesso.");
            preencherTarefas();
            jDateChooserAgenda.setEnabled(false);

            verificaSeHoje(jDateChooserAgenda.getDate());

            jButtonNovoActionPerformed(evt);
            jButtonSalvar.setEnabled(false);
            jButtonNovo.setEnabled(true);

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Erro ao agendar tarefa." + ex);
        }

        conexao.FecharConexao();
    }//GEN-LAST:event_jButtonSalvarActionPerformed

    private void jTabletarefasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTabletarefasMouseClicked

        if (this.getTitle().equals("Tarefas Agendadas")) {
            jButtonExcluir.setEnabled(false);
            jButtonNovo.setEnabled(false);
            jButtonFinalizar.setEnabled(true);
        } else {
            jButtonExcluir.setEnabled(true);
            jButtonSalvar.setEnabled(false);
            jButtonNovo.setEnabled(true);
        }

        jDateChooserAgenda.setEnabled(false);

        conexao.getConexaoSql();
        String id = "" + jTabletarefas.getValueAt(jTabletarefas.getSelectedRow(), 0);
        conexao.executaSql("select * from agenda_tarefas where id = '" + Integer.parseInt(id) + "' order by data_agendada");

        try {
            conexao.rs.first();

            Date data = conexao.rs.getDate("data_agendada");
            jDateChooserAgenda.setDate(data);

            String status = conexao.rs.getString("status");
            jComboBoxStatus.setSelectedItem(status);
            jTextFieldAssunto.setText(conexao.rs.getString("assunto"));
            jTextPaneDescricao.setText(conexao.rs.getString("descricao"));

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Erro......");
        }
        conexao.FecharConexao();

    }//GEN-LAST:event_jTabletarefasMouseClicked

