    public void verificaSeHoje(Date re) {
        Date data1 = re;
        Date data2 = new Date();
        if (data1.before(data2) || data1.equals(data2)) {
            TelaLogin.alerta = Integer.parseInt(minuto.format(new Date()))+1;
            JOptionPane.showMessageDialog(null, "MINUTO ("+ TelaLogin.alerta + ")  verificaseHoje" );
        }

       
    }

