    public String criptografiaToMD5(String senha) {
        String password1MD5 = null;
        //System.out.println("Senha original  " + senha);
        try {
            password1MD5 = ConvertPasswordToMD5.convertPasswordToMD5(senha);

            //System.out.println("Password1 em MD5: " + password1MD5);
        } catch (NoSuchAlgorithmException e) {
            e.printStackTrace();
        }
        return password1MD5;
    }

    public void preenchetabelausuarios() {
        conexao.getConexaoSql();
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"ID", "Usuários", "Nível", "Nome Completo", "Status"};

        conexao.executaSql("Select usu_cod, usu_usuario, usu_nivel, usu_nome, usu_status from usuarios order by usu_usuario");
        try {
            conexao.rs.first();
            do {
                dados.add(new Object[]{conexao.rs.getInt("usu_cod"), conexao.rs.getString("usu_usuario"), conexao.rs.getString("usu_nivel"), conexao.rs.getString("usu_nome"), conexao.rs.getString("usu_status")});
            } while (conexao.rs.next());

            ModeloTabela tabelasenha = new ModeloTabela(dados, colunas);
            jTableSenha.setModel(tabelasenha);
            jTableSenha.getColumnModel().getColumn(0).setPreferredWidth(50);
            jTableSenha.getColumnModel().getColumn(1).setPreferredWidth(100);
            jTableSenha.getColumnModel().getColumn(2).setPreferredWidth(150);
            jTableSenha.getColumnModel().getColumn(3).setPreferredWidth(250);
            jTableSenha.getColumnModel().getColumn(4).setPreferredWidth(100);
            jTableSenha.setAutoResizeMode(jTableSenha.AUTO_RESIZE_OFF);
            jTableSenha.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Nenhum usuários encontrado.");
        }

        conexao.FecharConexao();

    }

