    public void verificaTarefas(){
        conexao.getConexaoSql();
        try {
            String data = df.format(new Date());
            conexao.executaSql("select * from agenda_tarefas where data_agendada <= '" + data + "' and status = 'Agendada' order by data_agendada");
            conexao.rs.first();
            String status = conexao.rs.getString("status"); // só para gerar o erro do try catch
            TelaLogin.tarefas = 1; // exibe somente tarefas do dia
            TelaAgendaTarefas agtar = new TelaAgendaTarefas();
            
            TelaLogin.alerta = Integer.parseInt(minuto.format(new Date()));
            if (TelaLogin.alerta <= 49 ){
                TelaLogin.alerta = Integer.parseInt(minuto.format(new Date())) + 10 ;
                //JOptionPane.showMessageDialog(null, "MINUTO ("+ TelaLogin.alerta + ") Tela/Login menor q 49");
            }else{
                int calc;
                TelaLogin.alerta = Integer.parseInt(minuto.format(new Date())) + 10 ;
                calc = TelaLogin.alerta - 59;
                TelaLogin.alerta = calc;
                //JOptionPane.showMessageDialog(null, "MINUTO ("+ TelaLogin.alerta + ") Tela/Login menor q 49");
            }
            TelaLogin.visivel = "sim";
            agtar.setVisible(true);
        } catch (SQLException ex) {
           TelaLogin.visivel = "não";
        }
        
        conexao.FecharConexao();
        
    }
    
    
