    private void jButtonAcessarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAcessarActionPerformed
        conexao.getConexaoSql();

        conexao.executaSql("Select * from usuarios where usu_usuario ='" + jTextFieldUsuario.getText() + "'");
        try {
            conexao.rs.first();
            String senhabd = conexao.rs.getString("usu_senha");
            
            
            //****informações para validação de acessos
            nomeusu = conexao.rs.getString("usu_usuario");
            codusu = conexao.rs.getString("usu_cod");
            nivelusu = conexao.rs.getString("usu_nivel");
            numnivelusu = conexao.rs.getInt("usu_num_nivel");
            usuariocod = conexao.rs.getInt("usu_cod");
            usuperfil = conexao.rs.getString("usu_perfil");
            usuflag = 0;
            //********************************************************

            if (conexao.rs.getString("usu_status").equals("BLOQUEADO")) {
                JOptionPane.showMessageDialog(null, "Usuário com acesso bloqueado.");
                return;
            }

            try {
                String CompareMD5 = ConvertPasswordToMD5.convertPasswordToMD5(String.valueOf(jPasswordFieldSenha.getPassword()));

                if (jCheckBoxAlterarSenha.isSelected() && jButtonAcessar.getText().equals("Alterar Senha")) {
                    CompareMD5 = senhabd;
                }

                if (CompareMD5.equals(senhabd)) {

                    if (jCheckBoxAlterarSenha.isSelected() && jButtonAcessar.getText().equals("Alterar Senha")) {
                        String senha1 = ConvertPasswordToMD5.convertPasswordToMD5(String.valueOf(jPasswordFieldSenha.getPassword()));
                        String senha2 = ConvertPasswordToMD5.convertPasswordToMD5(String.valueOf(jPasswordFieldConfirmaSenha.getPassword()));
                        if (senha1.equals(senha2)) {
                            modelosenha.setSenha(senha1);
                            modelosenha.setId(conexao.rs.getInt("usu_cod"));
                            controlesenha.AlterarSenha(modelosenha);
                            jPasswordFieldSenha.setBackground(Color.white);
                            jPasswordFieldConfirmaSenha.setBackground(Color.white);
                        } else {
                            JOptionPane.showMessageDialog(null, "Senhas não conferem.");

                            jPasswordFieldSenha.setText("");
                            jPasswordFieldConfirmaSenha.setText("");
                            jPasswordFieldSenha.requestFocus();
                            return;
                        }
                        jPasswordFieldSenha.setText("");
                        jPasswordFieldConfirmaSenha.setText("");
                        jButtonAcessar.setText("Acessar");
                        jTextFieldUsuario.requestFocus();
                        jCheckBoxAlterarSenha.setSelected(false);
                        jLabelConfirmaSenha.setVisible(false);
                        jPasswordFieldConfirmaSenha.setVisible(false);

                    } else {
                        if (jCheckBoxAlterarSenha.isSelected()) {
                            jLabelConfirmaSenha.setVisible(true);
                            jPasswordFieldConfirmaSenha.setVisible(true);
                            jButtonAcessar.setText("Alterar Senha");
                            jPasswordFieldSenha.setText("");
                            jPasswordFieldSenha.requestFocus();
                            jPasswordFieldSenha.setBackground(Color.yellow);
                            jPasswordFieldConfirmaSenha.setBackground(Color.yellow);
                        } else {
                            TelaPrincipal telapri = new TelaPrincipal();
                            telapri.setVisible(true);
                            Aniversariantes niver = new Aniversariantes();
                            niver.setVisible(true);
                            dispose();
                            //****************
                            verificaTarefas();
                            
                        }
                    }

                } else {
                    JOptionPane.showMessageDialog(null, "Senha Inválida.");
                }

            } catch (NoSuchAlgorithmException ex) {
                Logger.getLogger(TelaLogin.class.getName()).log(Level.SEVERE, null, ex);
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Usuário não cadastrado.");
            //dispose();
        
        }


    }//GEN-LAST:event_jButtonAcessarActionPerformed

